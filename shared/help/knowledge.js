/**
 * تعريفات المعجم: كل مصطلح يحيل إلى صفحته، بنفس الـslug الذي تستعمله صفحة المعجم.
 * @type {HelpEntry[]}
 */
export const LEXICON_ENTRIES = (() => {
  const slugs = lexiconSlugById(lexiconTerms)
  const taken = new Set(slugs.values())
  for (const term of lexiconTerms) {
    if (!slugs.has(term.id)) slugs.set(term.id, uniqueLexiconSlug(term, taken))
  }
  return lexiconTerms
    .filter((term) => term.term_ar && term.definition)
    .map((term) => ({
      id: `lexicon-${term.id}`,
      title: term.term_fr ? `${term.term_ar} (${term.term_fr})` : term.term_ar,
      url: `/lexicon/${slugs.get(term.id)}`,
      keywords: [term.term_fr, term.category].filter(Boolean),
      body: term.definition,
    }))
})()

/** أسئلة صفحة الأسئلة الشائعة كمدخلات قابلة للبحث، وكلها تحيل إلى /faq. */
export const FAQ_ENTRIES = faqGroups.flatMap((group, gi) =>
  group.items.map((item, ii) => ({
    id: `faq-${gi}-${ii}`,
    title: item.question,
    url: "/faq",
    keywords: [],
    body: item.answer,
  })),
)

/** @returns {HelpEntry[]} */
export function allEntries() {
  return [...CURATED_ENTRIES, ...LEXICON_ENTRIES, ...FAQ_ENTRIES]
}
