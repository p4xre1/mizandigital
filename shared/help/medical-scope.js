// بوابة نطاق محافظة قبل البحث والتصحيح الإملائي: طلب العلاج ليس سؤالاً قانونياً.
// قواعد لفظية محددة، لا تشخيص طبي ولا ادعاء فهم دلالي شامل.
import { normalize } from "./retrieve.js"

export const MEDICAL_SCOPE_REPLY =
  "أنا مساعد لاستعمال ميزان الرقمية والعثور على محتواها، ولا أستطيع تشخيص الأعراض أو التوصية بدواء أو جرعة. بخصوص الأعراض التي تقلقك، استشر طبيبًا، واسأل طبيبًا أو صيدليًا قبل استعمال أي دواء."

const SYMPTOM_WORD = "(?:[وبفل]?ال|[وبفل])?(?:صداع|شقيقه|حمي|سعال|دوخه|غثيان|الم|الام|وجع)"
const SYMPTOMS = new RegExp(`(?:^|\\s)${SYMPTOM_WORD}(?:\\s|$)`)
const MEDICINE = /(?:^|\s)(?:[وبفل]?ال|[وبفل])?(?:دواء|ادويه|دوا|مسكن|مسكنات|جرعه|جرعات|علاج)(?:\s|$)/
const PERSONAL_SYMPTOM = new RegExp(
  `(?:^|\\s)(?:اشعر|اعاني|احس|عندي|عندنا|لدي|عنده|عندها|عند (?:طفلي|ابني|ابنتي))(?: من)? ${SYMPTOM_WORD}(?:\\s|$)`,
)
const TREATMENT_REQUEST = /(?:^|\s)(?:تنصحني|انصحني|توصيني|توصي|تقترح|ناخذ|ناخد|اخذ|اتناول|استعمل|نشرب|اعالج|نعالج|اخفف|نخفف)(?:\s|$)|(?:صف|اقترح|اختر) لي|(?:ما|شنو|اشنو) (?:هو |هي )?(?:(?:افضل|احسن) )?(?:الدواء|دواء|العلاج|علاج|الجرعه|جرعه|الدوا)|(?:كيف|كيفاش) (?:اعالج|نعالج|اتخلص)|كم (?:حبه|قرص|جرعه)/
const DARIJA_PAIN = /(?:راسي|بطني|ظهري) (?:كيضرني|كيوجعني|يولمني)/

/** لا يكفي ذكر «الطب» أو «الدواء»: أسئلة القوانين وحقوق المرضى تبقى قابلة للبحث. */
export function isMedicalAdviceRequest(text) {
  const n = normalize(text)
  const symptoms = SYMPTOMS.test(n) || DARIJA_PAIN.test(n)
  const medicine = MEDICINE.test(n)
  return PERSONAL_SYMPTOM.test(n) || DARIJA_PAIN.test(n) || ((symptoms || medicine) && TREATMENT_REQUEST.test(n))
}
