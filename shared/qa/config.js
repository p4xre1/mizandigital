// shared/qa/config.js
//
// كل الأوزان والحدود في مكان واحد. لا رقم سحري في باقي الوحدات.
// التغيير هنا يُختبر بـ tests/qa-benchmark.test.ts قبل أي نشر.
//
// الأوزان نسب نسبية بين الإشارات، وليست احتمالات. لا تعني أن الجواب صحيح قانونياً،
// بل أن النص يطابق السؤال بالقدر الذي تقيسه هذه الإشارات.

export const QA_CONFIG = {
  /** أقصى طول لسؤال المستخدم بعد التنظيف (الحد الكامل للرسالة يفرضه نقطة الطلب). */
  maxInputChars: 500,
  /** أقصى عدد رموز يُعالج في السؤال. ما زاد يُهمل بصمت ويُسجل في الحالة. */
  maxTokens: 60,
  /** أطول عبارة متعددة الكلمات تُستخرج للمطابقة الحرفية. */
  maxPhraseLength: 4,

  /** أوزان الإشارات في درجة المرشح. */
  weights: {
    /** عبارة حرفية متعددة الكلمات موجودة في النص. */
    exactPhrase: 3,
    /** اسم المصطلح كاملاً يرد في السؤال. */
    termMention: 6,
    /** BM25 على الجذور (فقط بعد المطابقة الحرفية). */
    bm25: 1,
    /** رقم الفصل أو المادة يطابق المرشح والقانون (إن ذُكر القانون). */
    articleRef: 10,
    /** رقم القانون (مثل 70.03) يطابق المرشح. */
    lawRef: 10,
    /** وزن السلطة: يُضرب في authority[kind]. */
    authority: 1,
  },

  /** سلطة المصدر (أعلى = أوثق). تُستعمل كقيد وكوزن معاً. */
  authority: {
    /** نص دستوري مُراجع مقابل النص الرسمي (targetVerified للإحالة أعلى). */
    constitution_text: 3,
    /** اقتباس من نص قانوني مُسند في المعجم. */
    code_text: 2.5,
    /** سجل أرشيف قانوني رسمي (يتطلب الحالة). */
    law_record: 3,
    /** تعريف معجمي منشور. */
    definition_published: 2,
    /** تعريف معجمي قيد المراجعة. */
    definition_internal: 1,
    /** صفحات الموقع والأسئلة الشائعة: للتنقل فقط، لا تُستعمل جواباً قانونياً. */
    site: 0.5,
  },

  /** حد الأدنى لدرجة المرشح حتى يُعتبر ذا صلة. */
  minScore: 3,
  /** نسبة تغطية كلمات السؤال المحتوى (بعد حذف كلمات الاستفهام والنية). */
  minCoverage: 0.5,
  /** إن كان المرشحان من مصطلحين مختلفين بدرجة قريبة (النسبة) ولا رقم يحسم، نطلب التوضيح. */
  clarifyRatio: 0.9,
  /** أقصى عدد خيارات في سؤال التوضيح. */
  maxClarifyOptions: 3,

  /** ميزانية الكلمات لكل نوع إجابة. القطع لا يدخل نصاً مُقتبساً، بل تُحذف الأدلة الأدنى. */
  answerBudgetWords: {
    definition: 250,
    conditions: 250,
    legislation_lookup: 250,
    comparison: 300,
    explanation: 250,
    lookup: 250,
  },

  /** أقصى عدد أدلة يُعرض في الجواب. */
  maxEvidence: 3,
}

/** @returns {typeof QA_CONFIG} نسخة مدموجة مع تخصيص جزئي (للاختبار والمعايرة). */
export function withConfig(overrides = {}) {
  return {
    ...QA_CONFIG,
    ...overrides,
    weights: { ...QA_CONFIG.weights, ...(overrides.weights || {}) },
    authority: { ...QA_CONFIG.authority, ...(overrides.authority || {}) },
    answerBudgetWords: { ...QA_CONFIG.answerBudgetWords, ...(overrides.answerBudgetWords || {}) },
  }
}
