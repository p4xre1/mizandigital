// المرحلة 6: تصنيف نية السؤال بقواعد حتمية وقابلة للاختبار. ليس فهماً دلالياً.
//
// الأنواع: definition (تعريف)، conditions (شروط وأركان واستثناءات)، procedure (إجراءات)،
// comparison (مقارنة)، legislation_lookup (نص فصل أو قانون)، explanation (شرح وتعليل)،
// lookup (غير محدد)، unsupported (لا نية قانونية واضحة).
//
// الترتيب مهم: المقارنة قبل الشروط، والشروط قبل النص، لأن "ما شروط الفصل 2" شرط لا نص.
// كل نوع يذكر الكلمات التي أثبتت النية، ليُختبر كل تصنيف على حدة.


const RULES = [
  {
    type: "comparison",
    patterns: [/(^| )(الفرق|الفروق|فرق|مقارنه|قارن|قارني|بين)( |$)/],
    requires: (n) => /(^| )بين /.test(n) || /(^| )(الفرق|الفروق|فرق|مقارنه|قارن)( |$)/.test(n),
  },
  {
    type: "conditions",
    patterns: [/(^| )(شروط|شرط|اركان|ركن|يشترط|يشترطه|متى|استثناء|استثناءات|الاستثناءات|صحه|صحيح|تصح|يصح)( |$)/],
  },
  {
    type: "procedure",
    patterns: [/(^| )(كيف|كيفيه|كيفاش|خطوات|خطوه|مراحل|اجراء|اجراءات|طريقه|شحال|فين|كيفاه)( |$)/],
  },
  {
    type: "legislation_lookup",
    patterns: [
      /(^| )(نص|نصوص|الفصل|فصل|الماده|ماده|الفصول|المواد|يجوز|يحق|يمكن|هل)( |$)/,
      /(^| )القانون رقم( |$)/,
      /(^| )رقم \d+(\.\d+)?( |$)/,
    ],
  },
  {
    type: "definition",
    patterns: [
      /(^| )ما (هو|هي|هوه|هيه|معني|المقصود|المقصود ب|تعني|يعني)( |$)/,
      /(^| )(عرف|عرفني|عرفلي|تعريف|شنو|شو|ماذا|ماهو|ماهي|chno|shno|chnou|ach)( |$)/,
      /(^| )(معني|مفهوم)( |$)/,
    ],
  },
  {
    type: "explanation",
    patterns: [/(^| )(اشرح|اشرحي|وضح|وضحي|علاش|لماذا|علل|سبب)( |$)/],
  },
]

/** كلمات استفهام ونية لا تدخل في حساب تغطية السؤال. */
export const QUESTION_AND_INTENT_WORDS = new Set([
  "ما", "هو", "هي", "هوه", "هيه", "ماذا", "شنو", "شو", "chno", "ach", "معني", "المقصود", "تعني", "يعني",
  "عرف", "عرفني", "تعريف", "مفهوم", "هل", "كيف", "متى", "فين", "شحال", "لماذا", "علاش", "اشرح", "وضح",
  "الفرق", "الفروق", "فرق", "بين", "و", "او", "في", "من", "عن", "على", "الي", "ب", "ل", "ك",
  "شروط", "شرط", "اركان", "ركن", "يشترط", "استثناء", "استثناءات", "الاستثناءات", "نص", "نصوص", "فصل",
  "الفصل", "الفصول", "ماده", "الماده", "المواد", "القانون", "رقم", "يجوز", "يحق", "يمكن", "مقارنه", "قارن",
  "ينص", "اعطني", "اعطيني", "ممكن", "عليه", "عليها", "يكون", "تكون", "يصح", "صح",
  "ان", "انه", "انها", "ذلك", "هذا", "هذه", "التي", "الذي",
])

/**
 * @param {string} normalized  النص المطبَّع للسؤال الأصلي (ويُضاف إليه النص المحوّل للدارجة)
 * @returns {{ type: string, signals: string[] }}
 */
export function classifyIntent(normalized) {
  for (const rule of RULES) {
    const hits = rule.patterns.filter((re) => re.test(normalized)).map((re) => String(re).slice(0, 40))
    const ok = hits.length > 0 && (rule.requires ? rule.requires(normalized) : true)
    if (ok) return { type: rule.type, signals: hits }
  }
  return { type: "lookup", signals: [] }
}

/**
 * الكلمات المحتوى: ما بقي بعد حذف الاستفهام والنية والأرقام والكيانات.
 * @param {string[]} tokens
 * @returns {string[]}
 */
export function contentTokens(tokens) {
  // الكلمة الاستفهامية قد تأتي ملتصقة بواو أو باء أو لام ("وما"، "فالمادة")، فتُفحص صيغها أيضاً.
  const isFunction = (t) => QUESTION_AND_INTENT_WORDS.has(t) || (/^[وفبلك]/.test(t) && QUESTION_AND_INTENT_WORDS.has(t.slice(1)))
  return tokens.filter((t) => !isFunction(t) && !/\d/.test(t) && t.length >= 2)
}
