/**
 * روابط التحميل في الأرشيف — مصدر واحد للحقيقة.
 *
 * لماذا وحدة مستقلة في shared/؟
 * --------------------------------
 * رابط التحميل يُقرأ في أربعة أماكن مختلفة يجب أن تتطابق حرفياً:
 *   1) الواجهة (ArchivePage) — زر «تحميل» في بطاقة الملف.
 *   2) scripts/generate-sitemap.mjs — هل يُنشر رابط /pdf/<slug> في الخريطة؟
 *   3) scripts/prerender.mjs — رابط التحميل داخل صفحة /pdf/<slug> الثابتة.
 *   4) scripts/generate-law-archive-snapshot.mjs — لقطة القوانين للصفحة الرئيسية.
 *
 * اسم الحقل نفسه يختلف بحسب المصدر، وهذا أصل الخلل:
 *   • docs.json (ملفات محلية)          → fileUrl
 *   • pdf_summaries (ملخصات مرفوعة)    → file_url
 *   • laws (نصوص قانونية)              → pdf_url
 * وكل جهة كانت تقرأ حقلاً واحداً فقط، فتظهر بطاقات برابط فارغ (`#`) أو
 * بـ undefined — زر تحميل لا يفتح شيئاً.
 *
 * القاعدة الحاكمة هنا
 * -------------------
 *   الرابط الفارغ لا يُعدّ رابطاً. لا `""`، لا `null`، لا `"#"`.
 *   أي سجلّ بلا رابط تحميل حقيقي لا يَظهر في الأرشيف ولا يُنشر في خريطة
 *   الموقع، إلا إذا كان يحمل نصّاً قانونياً كاملاً يُقرأ على الصفحة نفسها
 *   (حقل content في جدول laws) — فالنصّ وحده محتوى، والرابط إضافة عليه.
 */

/** هل هذه القيمة رابط تحميل حقيقي؟ (لا فراغ، ولا "#"، ولا مسافات فقط) */
export function hasDownloadLink(value) {
  const text = String(value ?? "").trim();
  return text !== "" && text !== "#";
}

/**
 * رابط التحميل لسجلّ أرشيف من أي مصدر (محلي، ملخص مرفوع، نص قانوني).
 * @returns {string} الرابط بعد التشذيب، أو "" إن لم يكن هناك رابط حقيقي.
 */
export function downloadLinkOf(item) {
  if (!item || typeof item !== "object") return "";
  // الترتيب مهم عند اجتماع الحقول: الرابط الأخص يفوز (pdf_url للنصوص
  // القانونية، file_url للملخصات المرفوعة، fileUrl للملفات المحلية).
  const value = item.pdf_url ?? item.file_url ?? item.fileUrl ?? "";
  return hasDownloadLink(value) ? String(value).trim() : "";
}

/** هل للسجلّ نصّ قانوني/وصفي يُقرأ على صفحته (لا رابط خارجي)؟ */
export function hasReadableText(item) {
  const text = String(item?.content ?? item?.description ?? "").trim();
  return text.length > 0;
}

/**
 * هل يستحق هذا السجلّ صفحة منشورة؟
 *
 * نعم إن كان له رابط تحميل حقيقي، أو نصّ قانوني كامل يُعرض على الصفحة.
 * لا إن كان بلا رابط وبلا نصّ: صفحته آنذاك بطاقة فارغة وزر ميت، ونشرها في
 * خريطة الموقع يعني رابطاً ميتاً للزاحف.
 */
export function isArchivableItem(item) {
  return downloadLinkOf(item) !== "" || hasReadableText(item);
}

/**
 * ترتيب العرض في الأرشيف: النصوص القانونية أولاً، ثم الملخصات.
 *
 * لماذا؟ النصوص القانونية هي المصدر الأول الذي يقصده الطالب والباحث، وهي
 * المراجع التي تُستشهد بها؛ الملخصات مواد مساعدة عليها. كان الترتيب السابق
 * يضع القوانين في آخر القائمة بعد عشرات الملخصات، فتظهر «مخفية» خلفها.
 *
 * @returns {number} مرتبة السجلّ (القوانين قبل الملخصات، والفرع قبل العام).
 */
export function archiveRank(item) {
  const type = String(item?.type ?? "").trim();
  if (type === "نصوص قانونية") return 0;
  if (type === "ملخصات") return 2;
  return 1;
}
